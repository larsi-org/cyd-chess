// same PIECE_SIZE/fill/outline shape (6 pieces, indexed PAWN..KING as
// 0..5, 1-bit bitmaps at PIECE_SIZE x PIECE_SIZE, 3 bytes/row MSB-first, a
// solid silhouette plus a second bitmap of interior line/stroke detail
// drawn over it in a contrasting color) is all drawPieceBitmap()/
// drawPiece() in the main .ino actually assume. MENU's PIECE SET screen
// picks which set drawPiece() reads via PIECE_FILL_SETS/PIECE_OUTLINE_SETS
// below, indexed by the sketch's own `pieceSet` global.
