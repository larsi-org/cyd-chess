// Chess piece graphics for cyd-chess -- kept in its own header, separate
// from the drawing logic in the main sketch, specifically so a different
// piece design can be dropped in later just by replacing this file's data:
// same PIECE_SIZE/PIECE_FILL/PIECE_OUTLINE shape (6 pieces, indexed
// PAWN..KING as 0..5, 1-bit bitmaps at PIECE_SIZE x PIECE_SIZE, 3 bytes/row
// MSB-first, PIECE_FILL the solid silhouette and PIECE_OUTLINE a second
// bitmap of interior line detail drawn over it in a contrasting color) is
// all drawPieceBitmap()/drawPiece() in the main .ino actually assume.
