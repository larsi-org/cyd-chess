// domain -- COPYING.md there states these particular images were
// published before 1922). Originally 46x48 PNGs where the white/black
// piece variants share an identical fill-and-outline shape and differ
// only by fill color (traditional two-tone chess-diagram coloring, not
// literal black/white) -- so PIECE_FILL here is each piece's *whole*
// silhouette (fill region unioned with the outline stroke, from the
// White variant), downscaled with Lanczos resampling and thresholded at
// 50% coverage; PIECE_OUTLINE is just the stroke pixels, thresholded
// lower (~24% coverage) since a 1-2px line's average coverage drops well
// below 50% after a ~2x downscale and would otherwise vanish. Indexed
// piece-1 (PAWN=1..KING=6 -> 0..5), matching this sketch's own piece-type
// numbering. Every piece but the Knight (which is directional on purpose)
// is bilaterally symmetric in a real chess set, but the source art itself
// wasn't -- pixel-diffing each source PNG against its own horizontal flip
// found up to ~28% asymmetric pixels (worst on Queen/King), most visible
// on the downscaled King's crown. Two approaches were tried and rejected
// before this one: unioning the fill and outline masks with their own
// mirror (each independently) turned busy outline detail -- the Queen's
// crown jewels -- solid across nearly the whole band, since a mirror-union
// at that layer's much lower (~24% vs. fill's 50%) threshold inflates
// coverage far more there; symmetrizing fill alone left fill and outline
// geometrically inconsistent, so fill poked out (stray same-color pixels)
// past where outline no longer bounded it on the side that grew. Fixed
// properly by symmetrizing the *source* image itself for these 5 pieces --
// mirroring one native-resolution half over the other, before deriving
// either mask -- so PIECE_FILL and PIECE_OUTLINE are always derived from
// the same already-symmetric source and stay geometrically consistent by
// construction, with no density inflation since nothing is unioned.
